"""data.py — Synthetic 4-feature tabular dataset for Gaussian-copula evaluation.

Generates i.i.d. samples from a fixed latent model:
  * x0, x1 : continuous, standard-normal marginals
  * x2     : discrete, 3 levels (0, 1, 2)
  * x3     : discrete, 4 levels (0, 1, 2, 3)
  * y      : binary label

Cross-feature correlations are introduced through a shared latent factor so that
the Gaussian copula generator has something to recover.  The label is a noisy
function of x0 and x2, giving the downstream logistic-regression task a signal.

Assumptions / limitations
-------------------------
* Data is i.i.d.; no temporal ordering exists.
* The latent model is fixed and known to the generator, but the *evaluator*
  (app.py) must treat the real data as the ground truth and never see the
  generator internals.
* Discrete features are generated by thresholding a continuous latent variable,
  which keeps the joint distribution smooth and makes rank-based copula fitting
  well-defined.
"""

from __future__ import annotations

import numpy as np


def _generate_latent(n: int, rng: np.random.Generator) -> np.ndarray:
    """Draw n samples from the 5-dimensional latent Gaussian.

    Returns an array of shape (n, 5) where columns 0-3 are the four feature
    latents and column 4 is the label latent.
    """
    # Latent factor structure:
    #   z0 = f1 * F + s0 * e0
    #   z1 = f2 * F + s1 * e1
    #   z2 = f3 * F + s2 * e2
    #   z3 = f4 * F + s3 * e3
    #   z4 = f5 * F + s4 * e4
    # F ~ N(0,1) is a shared factor; e_i ~ N(0,1) are idiosyncratic.
    F = rng.standard_normal(n)
    e = rng.standard_normal((n, 5))

    # Loadings chosen to give moderate (not trivial) correlations.
    loadings = np.array([0.55, 0.45, 0.40, 0.35, 0.50])
    # Idiosyncratic standard deviations so that each z_i has unit variance.
    idio_sd = np.sqrt(1.0 - loadings ** 2)

    Z = loadings * F[:, None] + idio_sd * e
    return Z


def _discretize(z: np.ndarray, n_levels: int) -> np.ndarray:
    """Map a standard-normal latent to 0..n_levels-1 via equal-probability bins."""
    # Inverse CDF of the standard normal at (k + 0.5) / n_levels
    from scipy.stats import norm

    thresholds = norm.ppf((np.arange(1, n_levels) + 0.5) / n_levels)
    return np.searchsorted(thresholds, z).astype(np.int64)


def make_dataset(seed: int = 42, n_samples: int = 256) -> tuple[np.ndarray, np.ndarray]:
    """Create a synthetic 4-feature tabular dataset with a binary label.

    Parameters
    ----------
    seed : int
        Random seed.  Different seeds produce different X.
    n_samples : int
        Number of rows.  Must be >= 32.

    Returns
    -------
    X : np.ndarray, shape (n_samples, 4)
        Columns: x0 (float), x1 (float), x2 (int 0-2), x3 (int 0-3).
    y : np.ndarray, shape (n_samples,)
        Binary label, values in {0, 1}.

    Raises
    ------
    ValueError
        If n_samples < 32.
    """
    if n_samples < 32:
        raise ValueError(f"n_samples must be >= 32, got {n_samples}")

    rng = np.random.default_rng(seed)
    Z = _generate_latent(n_samples, rng)

    # Continuous features: use latent columns 0 and 1 directly (already N(0,1)).
    x0 = Z[:, 0]
    x1 = Z[:, 1]

    # Discrete features: threshold latent columns 2 and 3.
    x2 = _discretize(Z[:, 2], n_levels=3)
    x3 = _discretize(Z[:, 3], n_levels=4)

    # Binary label: noisy logistic function of x0 and x2.
    #   logit(p) = 0.9 * x0 + 0.6 * (x2 - 1)
    # This gives the label a genuine dependence on x0 and x2, while x1 and x3
    # are marginally informative only through the shared factor.
    logit_p = 0.9 * x0 + 0.6 * (x2 - 1.0)
    p = 1.0 / (1.0 + np.exp(-logit_p))
    y = (rng.random(n_samples) < p).astype(np.int64)

    X = np.column_stack([x0, x1, x2, x3])
    return X, y
